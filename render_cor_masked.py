#!/usr/bin/env python
"""Corner-masked, size-refiltered re-render of the GFP counting tree (COR/Day_3 masked).

Builds a NEW preprocessing tree (default: ``NIfTIs_leica_masked/``) from the r1
Leica tree (``NIfTIs_leica/``) by **re-segmenting every series' fluor** at the
configured size filter (``config.COUNT_MIN_VOXELS`` = 60 voxels), and additionally
burning two black-out corner patches into the **COR/Day_3** series before
segmentation (they cover the noisy bottom-corner detector haze that inflated the
COR/Day_3 counts). The size filter is a global preprocessing knob, so it changes
counts for *every* series (WER, COR Day1/Day4 too), not just COR/Day_3.

Pipeline (mirrors ``sc3d convert`` re-run on the existing fluor + count):
  1. Copy the source tree -> masked tree (once; skip if present unless --force).
     This carries the ``_raw`` volumes and folder structure over unchanged.
  2. For every series: read the pristine (watermark-cleaned) fluor NIfTI from the
     source tree; if it is under ``COR/Day_3`` zero the two corner polygons
     (`preprocess.masking.COR_DAY3_PATCHES`) across all z; re-segment at
     ``--min-voxels``; overwrite the segmentation (and, for COR/Day_3, the fluor)
     in the masked tree.
  3. Re-count the whole masked tree -> ``<tree>/all_samples_counts.csv``.

Usage:
    PYTHONPATH=src python render_cor_masked.py                 # defaults (min-voxels=60)
    PYTHONPATH=src python render_cor_masked.py --force         # rebuild the copy
    PYTHONPATH=src python render_cor_masked.py --min-voxels 46 # reproduce the old filter
"""
from __future__ import annotations

import argparse
import logging
import shutil
from pathlib import Path

import SimpleITK as sitk

from sc3d import config
from sc3d.core.counting import count_tree
from sc3d.core.labeling import label_and_filter
from sc3d.core.segment import segment_fluorescence
from sc3d.core.stack import Stack
from sc3d.io.discovery import walk_segmentations
from sc3d.preprocess.masking import COR_DAY3_PATCHES, apply_black_patches

log = logging.getLogger("render_cor_masked")

# Series whose sample path starts with this get the corner masks.
MASK_PREFIX = "COR/Day_3/"


def _count_seg(seg: sitk.Image) -> int:
    """Object count for a segmentation image, matching `core.counting.count_stack`."""
    stack = Stack(sample="", segmentation=seg, fluor=None, spacing=tuple(seg.GetSpacing()))
    _, counts = label_and_filter(stack, min_voxels=config.MIN_VOXELS)
    return len(counts)


def rerender(src_root: Path, dst_root: Path, min_voxels: int) -> list[dict]:
    """Re-segment every series in `dst_root` at `min_voxels`; mask COR/Day_3. Report per series."""
    report: list[dict] = []
    for ref in walk_segmentations(src_root):
        sample = ref.sample
        masked = sample.startswith(MASK_PREFIX)
        if not ref.fluor_path.exists():
            log.warning("No fluor for %s — leaving copied segmentation as-is", sample)
            continue

        fluor = sitk.ReadImage(str(ref.fluor_path))
        n_ondisk = _count_seg(sitk.ReadImage(str(ref.seg_path))) if ref.seg_path.exists() else -1

        if masked:
            fluor = apply_black_patches(fluor, COR_DAY3_PATCHES)

        seg = segment_fluorescence(fluor, min_voxels=min_voxels)
        n_new = _count_seg(seg)

        dst_dir = dst_root / sample
        dst_dir.mkdir(parents=True, exist_ok=True)
        stem = ref.seg_path.name[: -len(f"{config.SEG_BASE}.nii.gz")]
        sitk.WriteImage(seg, str(dst_dir / f"{stem}{config.SEG_BASE}.nii.gz"))
        if masked:  # persist the masked fluor too (unmasked fluor is unchanged → keep the copy)
            sitk.WriteImage(fluor, str(dst_dir / f"{stem}{config.FLUOR_BASE}.nii.gz"))

        report.append({"sample": sample, "masked": masked, "on_disk": n_ondisk, "new": n_new})
        log.info("%s%s: on-disk(46)=%d -> min=%d => %d",
                 sample, "  [corner-masked]" if masked else "", n_ondisk, min_voxels, n_new)
    return report


def _write_readme(dst_root: Path, report: list[dict], min_voxels: int) -> None:
    day3 = [r for r in report if r["masked"]]
    lines = [
        "# Corner-masked + size-refiltered COR/Day_3 re-render",
        "",
        f"Independent re-render of `NIfTIs_leica/`: every series re-segmented at a "
        f"**{min_voxels}-voxel** minimum object-size filter, with two black-out corner",
        "patches burned into the **COR/Day_3** series before segmentation. Generated by",
        "`render_cor_masked.py`; counts in `all_samples_counts.csv`.",
        "",
        "Corner patches (image (x, y) pixels, origin top-left, all z-slices, COR/Day_3 only):",
        f"  - bottom-left : {list(COR_DAY3_PATCHES[0])}",
        f"  - bottom-right: {list(COR_DAY3_PATCHES[1])}",
        "",
        f"COR/Day_3 counts (previous 46-vox r1 render -> this {min_voxels}-vox masked render):",
    ]
    for r in day3:
        lines.append(f"  - {r['sample'].split('/')[-1]}: {r['on_disk']} -> {r['new']}")
    (dst_root / "README_masking.md").write_text("\n".join(lines) + "\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--src", type=Path, default=Path(config.LEICA_OUT_DIRNAME),
                    help=f"Source Leica NIfTI tree (default: {config.LEICA_OUT_DIRNAME}).")
    ap.add_argument("--dst", type=Path, default=Path("NIfTIs_leica_masked"),
                    help="Masked output tree / analysis folder (default: NIfTIs_leica_masked).")
    ap.add_argument("--min-voxels", type=int, default=config.COUNT_MIN_VOXELS, dest="min_voxels",
                    help=f"Minimum object size in voxels (default: {config.COUNT_MIN_VOXELS}).")
    ap.add_argument("--force", action="store_true",
                    help="Delete and rebuild the destination copy if it already exists.")
    args = ap.parse_args(argv)

    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s | %(message)s")

    if args.dst.exists() and args.force:
        log.info("Removing existing %s (--force)", args.dst)
        shutil.rmtree(args.dst)
    if not args.dst.exists():
        log.info("Copying %s -> %s", args.src, args.dst)
        shutil.copytree(args.src, args.dst)
    else:
        log.info("Reusing existing %s (pass --force to rebuild the copy)", args.dst)

    report = rerender(args.src, args.dst, args.min_voxels)

    out_csv = count_tree(args.dst, out_dir=args.dst)
    _write_readme(args.dst, report, args.min_voxels)
    log.info("Done. Counts: %s", out_csv)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
